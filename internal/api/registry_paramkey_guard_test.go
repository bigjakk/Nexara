// TestRegistryUndeclaredParamKeys_UnresolvableHandlerIsFlagged covers the
// fail-closed side of resolveHandlerDecl: a func literal has no
// *ast.FuncDecl of its own (funcKey only ever names a top-level
// declaration), so it cannot be walked at all — and "cannot verify" must
// be reported, not silently passed. The specific wording assertion
// (rather than a bare length check) is deliberate: it is what would have
// told this failure apart from the FileLine/"<autogenerated>" bug — a
// REAL handler's bound method value used to produce a "parse
// <autogenerated>: ..." error and STILL satisfy "len(got) == 1", which is
// exactly how that bug shipped unnoticed the first time.
func TestRegistryUndeclaredParamKeys_UnresolvableHandlerIsFlagged(t *testing.T) {
	reg := NewRegistry()
	reg.Register(registryProbeEndpointNoParams("/api/v1/probe",
		Permissions{Public: "synthetic route for the param-key guard test"},
		func(_ fiber.Ctx, _ *apischema.Params) error { return nil }))

	got := registryUndeclaredParamKeys(reg.Endpoints())
	if len(got) != 1 {
		t.Fatalf("violations = %v, want exactly 1", got)
	}
	if !strings.Contains(got[0], "no top-level function declaration named") {
		t.Errorf("violation = %q, want it to say no top-level declaration was found (a closure) — "+
			"not the <autogenerated> file-resolution failure this guard used to have", got[0])
	}
}
