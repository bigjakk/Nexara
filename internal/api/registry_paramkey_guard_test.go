// TestParamAccessorsCoversEveryStringKeyedMethod keeps paramAccessors
// honest against apischema.Params' actual method set: a future accessor
// (an OptStrings, say) that takes a leading string key but is never added
// to paramAccessors would silently escape registryUndeclaredParamKeys'
// walk — this makes that a build failure instead of a quiet gap.
func TestParamAccessorsCoversEveryStringKeyedMethod(t *testing.T) {
	typ := reflect.TypeOf(&apischema.Params{})
	for i := 0; i < typ.NumMethod(); i++ {
		m := typ.Method(i)
		if m.Func.Type().NumIn() < 2 {
			continue // no argument beyond the receiver (e.g. Raw)
		}
		if m.Func.Type().In(1).Kind() != reflect.String {
			continue // first argument is not a string key
		}
		if !paramAccessors[m.Name] {
			t.Errorf("apischema.Params.%s takes a leading string argument but is not in paramAccessors — "+
				"registryUndeclaredParamKeys will not check calls to it", m.Name)
		}
	}
}

// paramKeyGuardProbe is a small type living directly in this test file,
// used as a BOUND METHOD VALUE — h.undeclaredKey, not a package-level
// function — the way every real handler in this codebase actually is.
// See the file's top comment for why that distinction is the whole point:
// a package-level probe alone would not have caught resolveHandlerDecl's
// original bug. The receiver is named "h" specifically so calleeKey
// (rbac_route_guard_test.go) recognizes it as a receiver, matching the
// codebase-wide handler convention isReceiverName documents.
type paramKeyGuardProbe struct{}

func (h paramKeyGuardProbe) undeclaredKey(_ fiber.Ctx, p *apischema.Params) error {
	_ = p.String("undeclared_probe_key")
	return nil
}

func (h paramKeyGuardProbe) declaredKeys(_ fiber.Ctx, p *apischema.Params) error {
	_ = p.String("size")
	_, _ = p.OptInt("index")
	_ = p.Has("format")
	return nil
}

func (h paramKeyGuardProbe) dynamicKey(_ fiber.Ctx, p *apischema.Params) error {
	key := "size"
	_ = p.String(key)
	return nil
}

// callsHelperWithUndeclaredKey and helperReadsUndeclaredKey exist for
// TestRegistryUndeclaredParamKeys_TransitiveWalkCatchesAHelper: the
// undeclared key is read in a DIFFERENT function than the one Endpoint.Handler
// names.
func (h paramKeyGuardProbe) callsHelperWithUndeclaredKey(c fiber.Ctx, p *apischema.Params) error {
	return h.helperReadsUndeclaredKey(c, p)
}

func (h paramKeyGuardProbe) helperReadsUndeclaredKey(_ fiber.Ctx, p *apischema.Params) error {
	_ = p.String("undeclared_via_helper")
	return nil
}

// TestRegistryUndeclaredParamKeys_CatchesAnUndeclaredKey is the "prove it
// bites" test, driven over a BOUND METHOD VALUE — see paramKeyGuardProbe's
// doc comment for why that shape specifically is load-bearing here.
func TestRegistryUndeclaredParamKeys_CatchesAnUndeclaredKey(t *testing.T) {
	probe := paramKeyGuardProbe{}
	reg := NewRegistry()
	reg.Register(registryProbeEndpointNoParams("/api/v1/probe",
		Permissions{Public: "synthetic route for the param-key guard test"},
		probe.undeclaredKey))

	got := registryUndeclaredParamKeys(reg.Endpoints())
	if len(got) != 1 {
		t.Fatalf("violations = %v, want exactly 1", got)
	}
	if !strings.Contains(got[0], "undeclared_probe_key") {
		t.Errorf("violation = %q, want it to name the undeclared key", got[0])
	}
}

// TestRegistryUndeclaredParamKeys_DeclaredKeysPass is the negative case:
// every key the handler reads IS declared, across String/OptInt/Has, and
// none of it should be flagged.
func TestRegistryUndeclaredParamKeys_DeclaredKeysPass(t *testing.T) {
	probe := paramKeyGuardProbe{}
	reg := NewRegistry()
	reg.Register(registryProbeEndpoint("/api/v1/probe",
		Permissions{Public: "synthetic route for the param-key guard test"},
		probe.declaredKeys,
		apischema.Properties{
			"size":   {Type: apischema.String},
			"index":  {Type: apischema.Integer, Optional: true},
			"format": {Type: apischema.String, Optional: true},
		}))

	if got := registryUndeclaredParamKeys(reg.Endpoints()); len(got) != 0 {
		t.Errorf("violations = %v, want none — every key the handler reads is declared", got)
	}
}

